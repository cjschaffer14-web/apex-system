"""Lean (QuantConnect) <-> APEX.

What Lean adds: an institutional-grade event-driven backtester (multi-asset, fill/slippage/
fee/margin models, universe selection, portfolio construction, risk models) and the Lean
CLI/Research tooling. Lean is C# with a Python algorithm layer, so the bridge is file-based:
APEX exports episodes as custom data, and a Lean algorithm (backtest only) replays them
through Lean's own fill and portfolio models, which is an independent check on APEX's
book-walk PnL.
"""
import csv

from .common import require_safe_mode

COLUMNS = ['time', 'bid', 'ask', 'mid', 'edge_bps', 'allow']


def export_custom_data(path, rows, mode='backtest'):
    """rows: dicts with ts_ns, bid, ask, edge_bps, allow(bool). Lean custom CSV, UTC, one symbol per file."""
    require_safe_mode(mode)
    last = -1
    with open(path, 'w', newline='') as f:
        w = csv.writer(f)
        for r in rows:
            if r['ts_ns'] <= last:
                raise ValueError('timestamps must be strictly increasing')
            last = r['ts_ns']
            bid, ask = float(r['bid']), float(r['ask'])
            if not 0 < bid < ask:
                raise ValueError('crossed or non-positive quote')
            w.writerow([last // 1_000_000, bid, ask, (bid + ask) / 2, float(r['edge_bps']), int(bool(r['allow']))])
    return path


ALGORITHM_TEMPLATE = '''# Generated by apex_v2.frameworks.lean_bridge. Backtest only: run with `lean backtest`.
from AlgorithmImports import *
from datetime import datetime, timedelta

DATA = {data_path!r}


class ApexQuote(PythonData):
    def GetSource(self, config, date, isLive):
        return SubscriptionDataSource(DATA, SubscriptionTransportMedium.LocalFile, FileFormat.Csv)

    def Reader(self, config, line, date, isLive):
        if not line or not line[0].isdigit():
            return None
        p = line.split(",")
        q = ApexQuote()
        q.Symbol = config.Symbol
        q.Time = datetime(1970, 1, 1) + timedelta(milliseconds=int(p[0]))
        q.Value = float(p[3])
        q["bid"], q["ask"], q["edge"], q["allow"] = float(p[1]), float(p[2]), float(p[4]), int(p[5])
        return q


class ApexReplay(QCAlgorithm):
    def Initialize(self):
        if self.LiveMode:
            raise Exception("APEX bridge is backtest-only")
        self.SetCash(100000)
        self.sym = self.AddData(ApexQuote, "APEXQ", Resolution.Second).Symbol
        self.SetBrokerageModel(BrokerageName.Default)

    def OnData(self, data):
        if not data.ContainsKey(self.sym):
            return
        q = data[self.sym]
        if q["allow"] == 1 and not self.Portfolio.Invested:
            self.SetHoldings(self.sym, 0.1)
        elif q["allow"] == 0 and self.Portfolio.Invested:
            self.Liquidate()
'''


def render_algorithm(data_path):
    src = ALGORITHM_TEMPLATE.format(data_path=data_path)
    compile(src, 'apex_lean_algo', 'exec')
    return src
