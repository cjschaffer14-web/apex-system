"""Freqtrade -> APEX and APEX -> Freqtrade.

What Freqtrade adds: a mature candle backtester, hyperopt, walk-forward FreqAI (sklearn /
LightGBM / torch / RL) and ccxt-backed exchange access with dry-run mode. APEX uses it
for (a) L2 snapshots through ccxt, and (b) a strategy that *consumes* APEX's governor
verdicts, always in dry-run, as a second opinion on directional/market-making legs.
"""
import json
from .common import build_snapshot, require_mode


def snapshot_from_ccxt_l2(l2, venue, pair, fee_bps=None, request_ns=None, received_ns=None):
    """ccxt/freqtrade `exchange.fetch_l2_order_book(pair, limit)` dict -> BookSnapshot.
    Futures symbols such as 'BTC/USDT:USDT' are rejected by pair_name (spot only for now)."""
    ts = l2.get('timestamp')
    src = int(ts * 1_000_000) if ts else None  # ccxt timestamps are ms
    return build_snapshot(venue, 'freqtrade:' + venue, 'freqtrade', pair,
                          [(r[0], r[1]) for r in l2['bids']], [(r[0], r[1]) for r in l2['asks']],
                          request_ns=request_ns, received_ns=received_ns, source_ns=src, fee_bps=fee_bps)


def write_signal_file(path, verdicts, mode='shadow'):
    """verdicts: iterable of dicts {pair, ts_ms, action: 'allow'|'veto', edge_bps, reason}.
    Freqtrade polls this file; APEX stays the single authority on vetoes."""
    require_mode(mode)
    rows = []
    for v in verdicts:
        if v['action'] not in ('allow', 'veto'):
            raise ValueError('bad action')
        rows.append({k: v[k] for k in ('pair', 'ts_ms', 'action', 'edge_bps', 'reason') if k in v})
    with open(path, 'w') as f:
        json.dump({'mode': mode, 'verdicts': rows}, f, allow_nan=False)
    return len(rows)


def features_from_snapshots(snaps):
    """Rows for FreqAI/pandas: microstructure features APEX already trusts (validated books only)."""
    out = []
    for s in snaps:
        s.validate()
        b = s.book
        bid, ask = b.bids[0].price, b.asks[0].price
        bd = sum(x.size for x in b.bids[:5]); ad = sum(x.size for x in b.asks[:5])
        out.append({'ts_ns': s.received_ns, 'pair': b.pair, 'venue': s.economic_venue_id,
                    'mid': float((bid + ask) / 2), 'spread_bps': float((ask - bid) / ((bid + ask) / 2) * 10000),
                    'imbalance5': float((bd - ad) / (bd + ad))})
    return out


STRATEGY_TEMPLATE = '''"""Generated by apex_v2.frameworks.freqtrade_bridge. DRY-RUN ONLY."""
import json
from pandas import DataFrame
from freqtrade.strategy import IStrategy

SIGNAL_FILE = {signal_file!r}


class ApexGovernedStrategy(IStrategy):
    INTERFACE_VERSION = 3
    timeframe = "1m"
    can_short = False
    minimal_roi = {{"0": 0.01}}
    stoploss = -0.02

    def _allowed(self, pair):
        try:
            data = json.load(open(SIGNAL_FILE))
        except (OSError, ValueError):
            return False  # no verdict => no trade
        if data.get("mode") not in ("live", "shadow", "backtest"):
            return False
        latest = [v for v in data["verdicts"] if v.get("pair") == pair]
        return bool(latest) and latest[-1]["action"] == "allow"

    def populate_indicators(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        return dataframe

    def populate_entry_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe["enter_long"] = 1 if self._allowed(metadata["pair"]) else 0
        return dataframe

    def populate_exit_trend(self, dataframe: DataFrame, metadata: dict) -> DataFrame:
        dataframe["exit_long"] = 0
        return dataframe
'''


def render_strategy(signal_file):
    src = STRATEGY_TEMPLATE.format(signal_file=signal_file)
    compile(src, 'apex_strategy', 'exec')  # fail loudly on template errors
    return src
