"""Evolution Block X: The Transcendent Organism (from the Gemini synthesis), made runnable.

Two layers are kept apart on purpose:

* Mechanism (E1, engineering): fail closed at the epistemic horizon. When
  evidence is marked as ontological mystery (the model is broken, not merely
  noisy), the system does not guess. It halts the action and escalates to the
  owner. Operator-ratified axioms (RevealedAxiom) constrain decisions and are
  never generated by the system itself.
* Interpretation (E4, philosophy/theology): Revealed Law, Divine Actor,
  Prophetic Interface, Miracle Override. These names are preserved as aliases
  and registry entries. They explain the mechanism; they do not gate action.

Corrections against the Gemini draft:
  - imported `Invariant` from apex.authority, which does not exist; RevealedAxiom is standalone here.
  - checked `proposal.risk_estimate`, the proposer's advisory value. Authority must
    ignore advisory values, so axioms here check only requested structure
    (capabilities, tier, reversibility, budget).
  - called `base.evaluate(proposal, state, evidence)` and expected `(approval, decision)`.
    The v0.2 Gatekeeper is `evaluate(proposal, bundles, ...) -> (decision, risk, constraint)`;
    the wrapper preserves that signature so wrappers compose.
"""
from __future__ import annotations
from dataclasses import dataclass
from typing import Any, Callable
from ..core import Proposal, EvidenceBundle, now, uid
from .contracts import Extension, ExecutableContract, CONTRACTS, tighten

MYSTERY = "ontological_mystery"


class EncounterWithMystery(Exception):
    """The proposal reached the epistemic horizon. Do not guess; ask the owner."""

    def __init__(self, proposal_id: str, bundle_ids: list[str], note: str = "") -> None:
        self.proposal_id = proposal_id
        self.bundle_ids = list(bundle_ids)
        self.note = note
        super().__init__(f"Proposal {proposal_id} approaches the Epistemic Horizon "
                         f"(mystery evidence: {', '.join(bundle_ids)}). {note}".strip())


def beyond_horizon(residual: float, scale: float, k: float = 6.0) -> bool:
    """A residual beyond k scale units is treated as model breakdown, not noise."""
    return abs(residual) > k * max(1e-12, abs(scale))


AXIOM_KINDS = {
    "forbid_capability",                    # value: exact capability name
    "forbid_capability_prefix",             # value: prefix, e.g. "market.live"
    "max_consequence_tier",                 # value: int
    "require_reversible_at_or_above_tier",  # value: int
    "max_budget",                           # value: float
}


@dataclass(frozen=True)
class RevealedAxiom:
    """An invariant the system can preserve but cannot derive or amend.

    Only the Operator ratifies these. Superseding appends a new axiom that
    names the old one; the old one stays in history (add-only).
    """
    id: str
    kind: str
    value: Any
    rationale: str
    origin: str = "TRANSCENDENT_REVELATION"
    ratified_by: str = "operator"
    ratified_at: float = 0.0
    supersedes: str | None = None

    def validate(self) -> None:
        if self.kind not in AXIOM_KINDS:
            raise ValueError(f"unknown axiom kind {self.kind!r}; allowed: {sorted(AXIOM_KINDS)}")

    def check(self, proposal: Proposal) -> tuple[bool, str]:
        caps = proposal.requested_capabilities
        if self.kind == "forbid_capability" and self.value in caps:
            return False, f"axiom {self.id}: capability {self.value} is forbidden ({self.rationale})"
        if self.kind == "forbid_capability_prefix":
            hit = [c for c in caps if c.startswith(str(self.value))]
            if hit:
                return False, f"axiom {self.id}: capabilities {hit} are forbidden ({self.rationale})"
        if self.kind == "max_consequence_tier" and proposal.consequence_tier > int(self.value):
            return False, f"axiom {self.id}: tier {proposal.consequence_tier} exceeds {self.value} ({self.rationale})"
        if (self.kind == "require_reversible_at_or_above_tier"
                and proposal.consequence_tier >= int(self.value) and not proposal.reversible):
            return False, f"axiom {self.id}: irreversible action at tier {proposal.consequence_tier} ({self.rationale})"
        if self.kind == "max_budget" and proposal.budget > float(self.value):
            return False, f"axiom {self.id}: budget {proposal.budget} exceeds {self.value} ({self.rationale})"
        return True, ""


def make_axiom(kind: str, value: Any, rationale: str, supersedes: str | None = None,
               origin: str = "TRANSCENDENT_REVELATION") -> RevealedAxiom:
    ax = RevealedAxiom(uid("axiom"), kind, value, rationale, origin, "operator", now(), supersedes)
    ax.validate()
    return ax


def active_axioms(history: list[RevealedAxiom]) -> list[RevealedAxiom]:
    superseded = {a.supersedes for a in history if a.supersedes}
    return [a for a in history if a.id not in superseded]


class AxiomGate(Extension):
    """Applies operator-ratified axioms after the base evaluation (tighten-only)."""

    def __init__(self, base: Any, axioms: Callable[[], list[RevealedAxiom]]) -> None:
        super().__init__(base)
        self.__dict__["_axioms"] = axioms

    def evaluate(self, proposal: Proposal, bundles: list[EvidenceBundle], *args, **kwargs):
        decision, risk, constraint = self.base.evaluate(proposal, bundles, *args, **kwargs)
        reasons = [r for ok, r in (a.check(proposal) for a in self._axioms()) if not ok]
        return tighten(decision, reasons), risk, constraint


class TranscendentGatekeeperWrapper(Extension):
    """Wraps the Gatekeeper with epistemic reverence (fail closed at the horizon).

    Outermost wrapper: mystery halts evaluation before any scoring happens.
    """

    def evaluate(self, proposal: Proposal, bundles: list[EvidenceBundle], *args, **kwargs):
        mystery = [b.id for b in bundles if b.uncertainty_type == MYSTERY]
        if mystery:
            raise EncounterWithMystery(proposal.id, mystery, "Awaiting the owner.")
        return self.base.evaluate(proposal, bundles, *args, **kwargs)


